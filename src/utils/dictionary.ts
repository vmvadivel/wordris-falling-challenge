  // Rare: 3 points
  Q: 3, Z: 3, X: 3, J: 3,
  // Uncommon: 2 points
  K: 2, V: 2, B: 2, P: 2, W: 2, Y: 2, F: 2, G: 2, H: 2, M: 2,
  // Common: 1 point
  A: 1, E: 1, I: 1, O: 1, U: 1, L: 1, N: 1, R: 1, S: 1, T: 1, D: 1, C: 1
